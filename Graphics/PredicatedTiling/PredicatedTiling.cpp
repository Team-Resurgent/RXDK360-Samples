//--------------------------------------------------------------------------------------
// PredicatedTiling.cpp
//
// This sample shows how to use Predicated Tiling to render to a surface in tiled segments.
// This technique is essential for rendering to surfaces that are too large to fit into
// EDRAM all at once, such as a 1280x720 4x MSAA surface.  It can also be used for
// specialized offscreen rendering, such as creating a huge shadow buffer that would be
// too large for EDRAM.
//
// The sample takes tiling scenarios as input.  Examine the TILING_SCENARIO struct below
// and experiment with various scenarios by adding to the scenario lists.
//
// Predicated Tiling works by replaying a single command buffer several times.  Your
// rendering calls are largely unchanged, except they need to be surrounded by
// D3DDevice::BeginTiling() and D3DDevice::EndTiling().  Also, since Predicated Tiling
// resolves into a texture, you will need to use D3DDevice::Swap() to view the final
// image, instead of using D3DDevice::Present().
//
// Each draw command is predicated on results collected during the first pass.
// These results contain the screen space extents of each draw command (which is
// collected by the hardware), so draw commands played back for each tile only execute
// on the tile(s) that it affects.  You can override the predication by using
// D3DDevice::SetPredication(), if you are sure that a particular
// command or sequence of commands will always be on one specific tile.
// SetPredication() is demonstrated below to highlight the tile boundary.
//
// Postprocessing effects (tone mapping, etc) are ideally done using the final
// frontbuffer texture which contains the full image generated by Predicated Tiling.
//
// If you perform any rendering calls that could potentially affect your program's state,
// such as memexport shader usage or XPS procedural synthesis, keep in mind that
// Predicated Tiling will execute these rendering calls once per tile (i.e. multiple
// times per frame).  This may or may not be the desired functionality, depending on the
// situation.
//
// Xbox Advanced Technology Group.
// Copyright (C) Microsoft Corporation. All rights reserved.
//--------------------------------------------------------------------------------------
