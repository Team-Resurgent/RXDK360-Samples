HRESULT Sample::Initialize()
{
    m_matWorld = XMMatrixIdentity();
    m_vWorldLightDirection = XMVectorSet( 1, 0, 1, 1 );

    // If we are outputting an interlaced mode with less than 720 lines (360 lines per field),
    // we cannot use a 1920 x 1080 front buffer because the video scaler cannot downsample
    // that far.
    XVIDEO_MODE VideoMode;
    XGetVideoMode( &VideoMode );
    DWORD dwEffectiveHeight = VideoMode.dwDisplayHeight;
    if( VideoMode.fIsInterlaced )
        dwEffectiveHeight /= 2;
    if( ( 1080.0f / ( FLOAT )dwEffectiveHeight ) > 3.0f )
        m_bAllow1920x1080 = FALSE;
    else
        m_bAllow1920x1080 = TRUE;

    // Resize the Direct3D device ring buffer.
    // Resizing the ring buffer supports a larger or smaller amount of draw calls per scene.
    // The default is 2MB of secondary ring buffer; here we'll change that to 3MB.
    D3DRING_BUFFER_PARAMETERS RBParams = { 0 };
    RBParams.PrimarySize = 0;  // Direct3D will use the default size of 32KB
    RBParams.SecondarySize = 3 * 1024 * 1024;
    RBParams.SegmentCount = 0; // Direct3D will use the default segment count of 32

    // Setting the pPrimary and pSecondary members to NULL means that Direct3D will
    // allocate the ring buffers itself.  You can optionally provide a buffer that
    // you allocated yourself (it must be write-combined physical memory, aligned to
    // GPU_COMMAND_BUFFER_ALIGNMENT).
    RBParams.pPrimary = NULL;
    RBParams.pSecondary = NULL;

    m_pd3dDevice->SetRingBufferParameters( &RBParams );

    // Create font.
    if( FAILED( m_Font.Create( "game:\\Media\\Fonts\\Arial_16.xpr" ) ) )
        ATG::FatalError( "Could not load font." );

    // Confine text drawing to the title safe area
    m_Font.SetWindow( ATG::GetTitleSafeArea() );

    // Create mesh.
    if( FAILED( m_RobotMesh.Create( "game:\\Media\\Meshes\\Robot.xbg" ) ) )
        ATG::FatalError( "Could not load mesh." );

    // Create help screen.
    if( FAILED( m_Help.Create( "game:\\Media\\Help\\Help.xpr" ) ) )
        ATG::FatalError( "Could not load help resources." );

    // Buffers to hold compiled shaders and possible error messages
    ID3DXBuffer* pShaderCode = NULL;
    ID3DXBuffer* pErrorMsg = NULL;

    HRESULT hr = S_OK;

    // Compile vertex shader.
    hr = D3DXCompileShader( g_strVertexShaderProgram,
                            ( UINT )strlen( g_strVertexShaderProgram ),
                            NULL, NULL,
                            "main", "vs_3_0",
                            0, &pShaderCode, &pErrorMsg, NULL );
    if( FAILED( hr ) )
    {
        ATG::FatalError( pErrorMsg ? ( const CHAR* )pErrorMsg->GetBufferPointer()
                         : "Vertex shader compilation error." );
    }

    // Create vertex shader.
    m_pd3dDevice->CreateVertexShader( ( DWORD* )pShaderCode->GetBufferPointer(),
                                      &m_pVertexShader );

    // Shader code is no longer required.
    pShaderCode->Release();
    pShaderCode = NULL;

    // Compile pixel shader.
    hr = D3DXCompileShader( g_strPixelShaderProgram,
                            ( UINT )strlen( g_strPixelShaderProgram ),
                            NULL, NULL,
                            "main", "ps_3_0",
                            0, &pShaderCode, &pErrorMsg, NULL );
    if( FAILED( hr ) )
    {
        ATG::FatalError( pErrorMsg ? ( const CHAR* )pErrorMsg->GetBufferPointer()
                         : "Pixel shader compilation error." );
    }

    // Create pixel shader.
    m_pd3dDevice->CreatePixelShader( ( DWORD* )pShaderCode->GetBufferPointer(),
                                     &m_pPixelShader );

    // Shader code no longer required.
    pShaderCode->Release();
    pShaderCode = NULL;

    // Define the vertex elements.
    static const D3DVERTEXELEMENT9 VertexElements[] =
    {
        { 0,  0, D3DDECLTYPE_FLOAT3,   D3DDECLMETHOD_DEFAULT, D3DDECLUSAGE_POSITION, 0 },
        { 0, 12, D3DDECLTYPE_FLOAT3,   D3DDECLMETHOD_DEFAULT, D3DDECLUSAGE_NORMAL,   0 },
        { 0, 24, D3DDECLTYPE_FLOAT2,   D3DDECLMETHOD_DEFAULT, D3DDECLUSAGE_TEXCOORD, 0 },
        D3DDECL_END()
    };

    // Create a vertex declaration from the element descriptions.
    m_pd3dDevice->CreateVertexDeclaration( VertexElements, &m_pVertexDecl );

    // Create shaders for post effects.
    hr = D3DXCompileShader( g_strVertexShaderProgram,
                            ( UINT )strlen( g_strVertexShaderProgram ),
                            NULL, NULL,
                            "vs_main_post",
                            "vs_3_0",
                            0,
                            &pShaderCode,
                            &pErrorMsg,
                            NULL );
    if( FAILED( hr ) )
    {
        ATG::FatalError( pErrorMsg ? ( const CHAR* )pErrorMsg->GetBufferPointer()
                         : "Vertex shader compilation error." );
    }

    m_pd3dDevice->CreateVertexShader( ( DWORD* )pShaderCode->GetBufferPointer(),
                                      &m_pVertexShaderPost );

    pShaderCode->Release();
    pShaderCode = NULL;

    hr = D3DXCompileShader( g_strPixelShaderProgram,
                            ( UINT )strlen( g_strPixelShaderProgram ),
                            NULL, NULL,
                            "ps_main_post",
                            "ps_3_0",
                            0,
                            &pShaderCode,
                            &pErrorMsg,
                            NULL );
    if( FAILED( hr ) )
    {
        ATG::FatalError( pErrorMsg ? ( const CHAR* )pErrorMsg->GetBufferPointer()
                         : "Pixel shader compilation error." );
    }

    m_pd3dDevice->CreatePixelShader( ( DWORD* )pShaderCode->GetBufferPointer(),
                                     &m_pPixelShaderPost );

    pShaderCode->Release();
    pShaderCode = NULL;

    static const D3DVERTEXELEMENT9 VertexElementsPost[] =
    {
        { 0,  0, D3DDECLTYPE_FLOAT2,   D3DDECLMETHOD_DEFAULT, D3DDECLUSAGE_POSITION, 0 },
        D3DDECL_END()
    };

    m_pd3dDevice->CreateVertexDeclaration( VertexElementsPost,
                                           &m_pVertexDeclPost );

    ResetDevice();

    return S_OK;
}


HRESULT Sample::Update()
{
    // Update FPS in the timer class.
    m_Timer.MarkFrame();

    // Get input from controllers (check for exit button sequence).
    ATG::GAMEPAD* pGamepad = ATG::Input::GetMergedInput();

    // The A button cycles the scenario index.
    if( pGamepad->wPressedButtons & XINPUT_GAMEPAD_A )
    {
        m_dwScenarioIndex++;
        // If 1920 x 1080 front buffers can't be used due to the output display mode,
        // skip them in the rotation.
        while( !m_bAllow1920x1080 && g_TilingScenarios[ m_dwScenarioIndex ].dwScreenHeight == 1080 )
            m_dwScenarioIndex++;
        if( g_TilingScenarios[ m_dwScenarioIndex ].strScenarioName == NULL )
            m_dwScenarioIndex = 0;
        ResetDevice();
    }

    // The Y button toggles forced predication.
    if( pGamepad->wPressedButtons & XINPUT_GAMEPAD_Y )
        m_bForcedPredication = !m_bForcedPredication;

    // The Back button toggles the help screen.
    if( pGamepad->wPressedButtons & XINPUT_GAMEPAD_BACK )
        m_bDrawHelp = !m_bDrawHelp;

    // The X button changes camera distance.
    if( pGamepad->wPressedButtons & XINPUT_GAMEPAD_X )
    {
        if( m_fEyeRadius == 8.0f )
            m_fEyeRadius = 4.0f;
        else
            m_fEyeRadius = 8.0f;
    }

    // The B button toggles rotation.
    if( pGamepad->wPressedButtons & XINPUT_GAMEPAD_B )
        m_bRotating = !m_bRotating;

    // View matrix
    FLOAT fTime = ( FLOAT )m_Timer.GetAppTime();
    if( !m_bRotating )
        fTime = -XM_PIDIV2 / 0.3f;
    XMVECTOR vEyePt = XMVectorSet( cosf( 0.3f * fTime ) * m_fEyeRadius, 0.0f,
                                   sinf( 0.3f * fTime ) * m_fEyeRadius, 0.0f );
    XMVECTOR vLookatPt = XMVectorSet( 0.0f, -0.2f, 0.0f, 0.0f );
    XMVECTOR vUp = XMVectorSet( 0.0f, 1.0f, 0.0f, 0.0f );
    m_matView = XMMatrixLookAtLH( vEyePt, vLookatPt, vUp );

    // World*view*projection
    m_matWVP = m_matWorld * m_matView * m_matProj;

    // Update robot mesh constants.
    m_RobotMesh.m_matWorld = m_matWorld;
    m_RobotMesh.m_matViewProj = m_matView * m_matProj;
    m_RobotMesh.m_vWorldLightDirection = m_vWorldLightDirection;

    return S_OK;
}


HRESULT Sample::Render()
{
    // Set our tiled render target.
    m_pd3dDevice->SetRenderTarget( 0, m_pTilingRenderTarget );
    m_pd3dDevice->SetDepthStencilSurface( m_pTilingDepthStencil );

    const TILING_SCENARIO& CurrentScenario = g_TilingScenarios[m_dwScenarioIndex];

    PIXBeginNamedEvent( 0xFFFFFFFF, "Scene Render" );

    D3DVECTOR4 ClearColor = { 0, 0, 0, 0 };
    BOOL bNeedTiling = ( CurrentScenario.dwTileCount > 1 );
    if( bNeedTiling )
    {
        // Begin tiling.  We specify the tile count, the tiling rectangles, and the
        // color and Z/stencil values to clear the tiling rendertarget with for each tile.
        m_pd3dDevice->BeginTiling(
            CurrentScenario.dwTilingFlags,
            CurrentScenario.dwTileCount,
            CurrentScenario.TilingRects,
            &ClearColor, 1.0f, 0L );
    }
    else
    {
        // We're not tiling in this scenario.  Just clear the rendertargets.
        m_pd3dDevice->Clear( 0, NULL,
                             D3DCLEAR_TARGET | D3DCLEAR_ZBUFFER,
                             0, 1.0f, 0 );

    }

    // Begin Z pass.  The Z pass is a subset of the full scene rendering.
    m_pd3dDevice->BeginZPass( 0 );

    // Render the scene.
    RenderScene();

    // End Z pass.
    m_pd3dDevice->EndZPass();

    if( bNeedTiling )
    {
        // End tiling.  This will cause the accumulated command buffer to be replayed
        // for each tile, predicated upon the boundaries of each tile.  At the end of
        // each tile's rendering, it will be resolved into a section of the front buffer
        // texture.
        m_pd3dDevice->EndTiling( D3DRESOLVE_RENDERTARGET0 |
                                 D3DRESOLVE_ALLFRAGMENTS |
                                 D3DRESOLVE_CLEARRENDERTARGET |
                                 D3DRESOLVE_CLEARDEPTHSTENCIL,
                                 NULL, m_pSceneResolveTexture,
                                 &ClearColor, 1.0f, 0L, NULL );
    }
    else
    {
        // We're not tiling in this scenario.  Just resolve rendertarget 0 to the
        // scene resolve texture.
        m_pd3dDevice->Resolve( D3DRESOLVE_RENDERTARGET0 |
                               D3DRESOLVE_CLEARRENDERTARGET,
                               NULL,
                               m_pSceneResolveTexture,
                               NULL, 0, 0,
                               &ClearColor, 1.0f, 0, NULL );
    }

    PIXEndNamedEvent();

    PIXBeginNamedEvent( 0xFFFFFFFF, "Post Effects" );

    // Set the full screen rendertarget.
    m_pd3dDevice->SetRenderTarget( 0, m_pPostRenderTarget );
    m_pd3dDevice->SetDepthStencilSurface( NULL );

    // Copy scene resolve texture back into EDRAM.
    // This is where you could apply any post effects to the scene texture, such as
    // high dynamic range tone mapping, depth of field, and more.
    // In this case, we're just copying the pixels back with no modification.
    m_pd3dDevice->SetVertexShader( m_pVertexShaderPost );
    m_pd3dDevice->SetPixelShader( m_pPixelShaderPost );
    m_pd3dDevice->SetVertexDeclaration( m_pVertexDeclPost );
    m_pd3dDevice->SetTexture( 0, &m_SceneResolveTextureAs16SRGB );

    // 3 2D corners are needed to draw a rect primitive.  The vertex shader will
    // generate proper 4D positions and 2D texture coordinates from this data.
    FLOAT fRectCorners[] = { -1, 1, 1, 1, -1, -1 };
    m_pd3dDevice->DrawPrimitiveUP( D3DPT_RECTLIST,
                                   1,
                                   ( const VOID* )fRectCorners,
                                   2 * sizeof( FLOAT ) );

    PIXEndNamedEvent();

    PIXBeginNamedEvent( 0xFFFFFFFF, "UI Render" );

    // Render UI.
    RenderUI();

    PIXEndNamedEvent();

    // Synchronize to presentation interval before the final resolve, so we do
    // not see tearing at 30Hz or 60Hz presentation intervals.
    m_pd3dDevice->SynchronizeToPresentationInterval();

    // Resolve the rendered scene back to the front buffer.
    m_pd3dDevice->Resolve( D3DRESOLVE_RENDERTARGET0 | D3DRESOLVE_CLEARRENDERTARGET,
                           NULL,
                           m_pFrontBufferTexture,
                           NULL,
                           0, 0,
                           &ClearColor,
                           1.0f, 0, NULL );

    // Swap to the current front buffer, so we can see it on screen.
    m_pd3dDevice->Swap( m_pFrontBufferTexture, NULL );

    return S_OK;
}


//--------------------------------------------------------------------------------------
// Name: main()
// Desc: Entry point to the program
//--------------------------------------------------------------------------------------
INT __cdecl main()
{
    Sample PredicatedTilingSample;

    // Set up the structure used to create the D3DDevice.
    // We don't need any back buffers for predicated tiling, since we will be creating
    // our own.  We also don't need depth/stencil created for us automatically.
    D3DPRESENT_PARAMETERS& d3dpp = PredicatedTilingSample.m_d3dpp;
    ZeroMemory( &d3dpp, sizeof( D3DPRESENT_PARAMETERS ) );
    d3dpp.BackBufferWidth = 1280;
    d3dpp.BackBufferHeight = 720;
    d3dpp.BackBufferFormat = ( D3DFORMAT )MAKESRGBFMT( D3DFMT_A8R8G8B8 );
    d3dpp.MultiSampleType = D3DMULTISAMPLE_NONE;
    d3dpp.MultiSampleQuality = 0;
    d3dpp.BackBufferCount = 0;
    d3dpp.EnableAutoDepthStencil = FALSE;
    d3dpp.DisableAutoBackBuffer = TRUE;
    d3dpp.DisableAutoFrontBuffer = TRUE;
    d3dpp.AutoDepthStencilFormat = D3DFMT_D24S8;
    d3dpp.SwapEffect = D3DSWAPEFFECT_DISCARD;
    d3dpp.PresentationInterval = D3DPRESENT_INTERVAL_IMMEDIATE;

    PredicatedTilingSample.m_dwDeviceCreationFlags = D3DCREATE_BUFFER_2_FRAMES;

    PredicatedTilingSample.Run();
}
