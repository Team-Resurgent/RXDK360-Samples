//--------------------------------------------------------------------------------------
// Name: LargestTileRectSize()
// Desc: Returns the dimensions that fit the largest rectangle(s) out of the tiling
//       rectangles.
//--------------------------------------------------------------------------------------
VOID LargestTileRectSize( const TILING_SCENARIO& Scenario, D3DPOINT* pMaxSize )
{
    pMaxSize->x = 0;
    pMaxSize->y = 0;
    for( DWORD i = 0; i < Scenario.dwTileCount; i++ )
    {
        DWORD dwWidth = Scenario.TilingRects[i].x2 - Scenario.TilingRects[i].x1;
        DWORD dwHeight = Scenario.TilingRects[i].y2 - Scenario.TilingRects[i].y1;
        if( dwWidth > ( DWORD )pMaxSize->x )
            pMaxSize->x = dwWidth;
        if( dwHeight > ( DWORD )pMaxSize->y )
            pMaxSize->y = dwHeight;
    }
}


//--------------------------------------------------------------------------------------
// Name: ResetDevice()
// Desc: Rebuilds all rendertargets and resolve textures, and  
//--------------------------------------------------------------------------------------
VOID Sample::ResetDevice()
{
    HRESULT hr;

    // Clean out the D3D device before destroying any resources.  D3D will
    // assert if a resource is destroyed while still selected into a D3D
    // device.
    m_pd3dDevice->UnsetAll();

    // Destroy resources
    SAFE_RELEASE( m_pTilingRenderTarget );
    SAFE_RELEASE( m_pTilingDepthStencil );
    SAFE_RELEASE( m_pPostRenderTarget );

    // Destroy frontbuffer and scene resolve textures.
    SAFE_RELEASE( m_pFrontBufferTexture );
    SAFE_RELEASE( m_pSceneResolveTexture );

    // Setup the presentation parameters
    const TILING_SCENARIO& CurrentScenario = g_TilingScenarios[m_dwScenarioIndex];

    DWORD dwFrontBufferWidth = CurrentScenario.dwScreenWidth;
    DWORD dwFrontBufferHeight = CurrentScenario.dwScreenHeight;

    // Set viewport.
    D3DVIEWPORT9 Viewport;
    Viewport.Width = dwFrontBufferWidth;
    Viewport.Height = dwFrontBufferHeight;
    Viewport.X = 0;
    Viewport.Y = 0;
    Viewport.MinZ = 0.0f;
    Viewport.MaxZ = 0.0f;
    m_pd3dDevice->SetViewport( &Viewport );

    // Set up tiling front buffer texture.
    // These are the size of your desired rendering surface (in this case, the whole
    // screen).
    // We also create a scene resolve texture here, which will be used to hold the
    // results of predicated tiling.  If we were tiling directly to the front buffer,
    // we would require 2 front buffers used on even-odd frames, to avoid visual
    // tearing.
    m_pd3dDevice->CreateTexture( dwFrontBufferWidth,
                                 dwFrontBufferHeight,
                                 1, 0,
                                 ( D3DFORMAT )MAKESRGBFMT( D3DFMT_LE_X8R8G8B8 ),
                                 D3DPOOL_DEFAULT,
                                 &m_pFrontBufferTexture,
                                 NULL );

    m_pd3dDevice->CreateTexture( dwFrontBufferWidth,
                                 dwFrontBufferHeight,
                                 1, 0,
                                 ( D3DFORMAT )MAKESRGBFMT( D3DFMT_X8R8G8B8 ),
                                 D3DPOOL_DEFAULT,
                                 &m_pSceneResolveTexture,
                                 NULL );

    m_SceneResolveTextureAs16SRGB = *m_pSceneResolveTexture;

    // Set up an alias of the resolve texture as an AS_16 sRGB format, since the GPU can't resolve 
    // to an AS_16_16_16_16 format. 
    // Alias this texture so there's no loss of precision when sampling the texture in the shader. If using
    // a standard SRGB format, the sRGB->Linear conversion happens with 8 bit precision, resulting 
    // in a loss of data. Using an AS_16 sRGB format causes the conversion to happen at 16-bit precision,
    // meaning no precision is lost.
    ATG::ConvertTextureToAs16SRGBFormat( &m_SceneResolveTextureAs16SRGB );

    if( NULL == m_pFrontBufferTexture || NULL == m_pSceneResolveTexture )
    {
        ATG::FatalError( "Could not create front buffer or scene resolve texture." );
    }

    // Record the size of one of the frontbuffers.
    m_dwFrontBufferSizeBytes = dwFrontBufferWidth * dwFrontBufferHeight * sizeof( DWORD );

    // Aspect ratio for HiDef displays is always 16x9 but our buffers may not be.
    FLOAT fAspectRatio = 16.0f / 9.0f; //( FLOAT )dwFrontBufferWidth / ( FLOAT )dwFrontBufferHeight;

    // Set up projection matrix
    m_matProj = XMMatrixPerspectiveFovLH( XM_PIDIV4, fAspectRatio, 1.0f, 200.0f );

    // Find largest tiling rect size
    D3DPOINT LargestTileSize;
    LargestTileRectSize( CurrentScenario, &LargestTileSize );

    // Create color and depth/stencil rendertargets.
    // These rendertargets are where Predicated Tiling will render each tile.  Therefore,
    // these rendertargets should be set up with all rendering quality settings you desire,
    // such as multisample antialiasing.
    // Note how we use the dimension of the largest tile rectangle to define how big the
    // rendertargets are.
    DWORD dwTileWidth = 0;
    DWORD dwTileHeight = 0;
    switch( CurrentScenario.MSAAType )
    {
        case D3DMULTISAMPLE_NONE:
            dwTileWidth = XGNextMultiple( LargestTileSize.x, GPU_EDRAM_TILE_WIDTH_1X );
            dwTileHeight = XGNextMultiple( LargestTileSize.y, GPU_EDRAM_TILE_HEIGHT_1X );
            break;
        case D3DMULTISAMPLE_2_SAMPLES:
            dwTileWidth = XGNextMultiple( LargestTileSize.x, GPU_EDRAM_TILE_WIDTH_2X );
            dwTileHeight = XGNextMultiple( LargestTileSize.y, GPU_EDRAM_TILE_HEIGHT_2X );
            break;
        case D3DMULTISAMPLE_4_SAMPLES:
            dwTileWidth = XGNextMultiple( LargestTileSize.x, GPU_EDRAM_TILE_WIDTH_4X );
            dwTileHeight = XGNextMultiple( LargestTileSize.y, GPU_EDRAM_TILE_HEIGHT_4X );
            break;
    }

    if( CurrentScenario.dwTileCount > 1 )
    {
        // Expand tile surface dimensions to texture tile size, if it isn't already
        dwTileWidth = XGNextMultiple( dwTileWidth, GPU_TEXTURE_TILE_DIMENSION );
        dwTileHeight = XGNextMultiple( dwTileHeight, GPU_TEXTURE_TILE_DIMENSION );
    }

    // Use custom EDRAM allocation to create the rendertargets.
    // The color rendertarget is placed at address 0 in EDRAM.
    D3DSURFACE_PARAMETERS SurfaceParams;
    memset( &SurfaceParams, 0, sizeof( D3DSURFACE_PARAMETERS ) );
    SurfaceParams.Base = 0;
    hr = m_pd3dDevice->CreateRenderTarget( dwTileWidth,
                                           dwTileHeight,
                                           ( D3DFORMAT )MAKESRGBFMT( D3DFMT_A8R8G8B8 ),
                                           CurrentScenario.MSAAType,
                                           0, FALSE,
                                           &m_pTilingRenderTarget,
                                           &SurfaceParams );
    if( FAILED( hr ) )
    {
        ATG::FatalError( "Cannot create tiling rendertarget.\n" );
    }

    // Record the size of the created rendertarget, and then set up allocation
    // for the next rendertarget right after the end of the first rendertarget.
    // Put the hierarchical Z buffer at the start of hierarchical Z memory.
    m_dwTileTargetSizeBytes = m_pTilingRenderTarget->Size;
    SurfaceParams.Base = m_dwTileTargetSizeBytes / GPU_EDRAM_TILE_SIZE;
    SurfaceParams.HierarchicalZBase = 0;

    hr = m_pd3dDevice->CreateDepthStencilSurface( dwTileWidth,
                                                  dwTileHeight,
                                                  D3DFMT_D24S8,
                                                  CurrentScenario.MSAAType,
                                                  0, FALSE,
                                                  &m_pTilingDepthStencil,
                                                  &SurfaceParams );
    if( FAILED( hr ) )
    {
        ATG::FatalError( "Cannot create tiling depth/stencil.\n" );
    }
    m_dwTileDepthStencilSizeBytes = m_pTilingDepthStencil->Size;

    // Create the post effects render target and depth/stencil surfaces.
    // These surfaces have no MSAA, and are used for post effects rendering and UI
    // rendering, after the tiled scene rendering is complete.
    SurfaceParams.Base = 0;
    hr = m_pd3dDevice->CreateRenderTarget( dwFrontBufferWidth,
                                           dwFrontBufferHeight,
                                           ( D3DFORMAT )MAKESRGBFMT( D3DFMT_A8R8G8B8 ),
                                           D3DMULTISAMPLE_NONE,
                                           0, FALSE,
                                           &m_pPostRenderTarget,
                                           &SurfaceParams );
    if( FAILED( hr ) )
    {
        ATG::FatalError( "Cannot create post effects rendertarget.\n" );
    }

    // If the front buffer size has changed, update the presentation parameters and
    // reset the D3D device.  Also set the font window to the new safe rectangle.
    if( dwFrontBufferHeight != m_d3dpp.BackBufferHeight ||
        dwFrontBufferWidth != m_d3dpp.BackBufferWidth )
    {
        m_d3dpp.BackBufferHeight = dwFrontBufferHeight;
        m_d3dpp.BackBufferWidth = dwFrontBufferWidth;
        m_pd3dDevice->Reset( &m_d3dpp );
        m_Font.SetWindow( ATG::GetTitleSafeArea() );
    }

    // Set up the screen extents query mode that tiling will use.
    m_pd3dDevice->SetScreenExtentQueryMode( CurrentScenario.ScreenExtentQueryMode );
}


//--------------------------------------------------------------------------------------
// Name: RenderScene()
// Desc: Sets some renderstate and draws the robot mesh.
//--------------------------------------------------------------------------------------
VOID Sample::RenderScene()
{
    // Set renderstate.
    m_pd3dDevice->SetRenderState( D3DRS_ZENABLE, TRUE );

    // Set shaders.
    m_pd3dDevice->SetVertexShader( m_pVertexShader );
    m_pd3dDevice->SetPixelShader( m_pPixelShader );
    m_pd3dDevice->SetVertexDeclaration( m_pVertexDecl );

    // Set shader constants.
    m_pd3dDevice->SetVertexShaderConstantF( 0, ( FLOAT* )&m_matWVP, 4 );

    // Optionally force the robot to only render on tile 1.
    if( m_bForcedPredication )
    {
        m_pd3dDevice->SetPredication( D3DPRED_TILE( 1 ) );
    }

    // Render the robot.
    m_RobotMesh.Render( ATG::MESH_NOTEXTURES | ATG::MESH_NOVERTEXDECL | ATG::MESH_NOFVF );

    // Reset predication to default.
    if( m_bForcedPredication )
    {
        m_pd3dDevice->SetPredication( 0 );
    }
}


