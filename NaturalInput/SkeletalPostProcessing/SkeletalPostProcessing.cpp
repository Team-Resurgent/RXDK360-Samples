//--------------------------------------------------------------------------------------
// SkeletalPostProcessing.cpp
//
// Demonstrates a variety of skeleton joint data postprocessing filters.  These filters
// are useful for refining skeleton joint positions for certain game scenarios where
// joint position data needs to be more consistent for gameplay or aesthetic reasons.
// Some filters are intended for use in general situations, while others may be needed
// only in very specific situations.  Finally, each filter usually presents a tradeoff
// between motion fidelity and consistency - for example, the arms up filter can
// provide much more consistent arm positions when the user raises their arms above their
// head, but the filter removes some expressiveness in this scenario, such as the user
// waving their hands above their head.
//
