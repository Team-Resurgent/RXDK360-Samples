//--------------------------------------------------------------------------------------
// Name: class SampleDebugRenderer
// Desc: Implements the IFilterDebugRenderer class, which is used to present debug messages
// generated by skeleton filters.  This interface allows the skeleton filters to avoid
// taking a dependency on title-specific UI presentation code.  This specific implementation
// draws the debug messages on the right side of the sample's display, using the ATG::Font
// text drawing class.
//--------------------------------------------------------------------------------------
class SampleDebugRenderer : public IFilterDebugRenderer
{
protected:
    ATG::Font* m_pFont;
    FLOAT m_YPos;

public:
    SampleDebugRenderer( ATG::Font* pFont )
    {
        m_pFont = pFont;
        m_YPos = 0.0f;
    }
    
    virtual VOID SetTextYPos( FLOAT fYPos )
    {
        m_YPos = fYPos;
    }

    virtual FLOAT GetTextYPos() const
    {
        return m_YPos;
    }

    virtual VOID DrawTextLine( FLOAT fXScale, FLOAT fYScale, DWORD Color, FLOAT fRightOffset, BOOL bNewline, const WCHAR* strFormat, ... )
    {
        WCHAR strLine[1024];
        va_list pArgList;
        va_start( pArgList, strFormat );
        _vsnwprintf_s( strLine, _TRUNCATE, strFormat, pArgList );
        va_end( pArgList );

        m_pFont->SetScaleFactors( fXScale, fYScale );
        m_pFont->DrawText( -fRightOffset, m_YPos, Color, strLine, ATGFONT_RIGHT );

        if( bNewline )
        {
            DrawEmptyLine( fYScale );
        }
    }

    virtual VOID DrawEmptyLine( FLOAT fYScale )
    {
        m_YPos += 20.0f * fYScale;
    }

protected:
    virtual VOID StartRendering()
    {
        m_YPos = 60.0f;
        m_pFont->SetScaleFactors( 1, 1 );
        m_pFont->Begin();
    }

    virtual VOID EndRendering()
    {
        m_pFont->End();
        m_pFont->SetScaleFactors( 1, 1 );
    }
};

